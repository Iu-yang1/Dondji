const char *UI_MENU_GetMenuTitle(const t_menu_item *item)
{
    const char *title;

    if (item == NULL)
        return "";
    if (gUiLanguage != UI_LANGUAGE_CN)
        return item->name;

    if (item->menu_id < (sizeof(gMenuTitleCN) / sizeof(gMenuTitleCN[0])))
    {
        title = gMenuTitleCN[item->menu_id];
        if (title != NULL)
            return title;
    }

    return item->name;
}
